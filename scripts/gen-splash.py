#!/usr/bin/env python3
"""Generate kernel/kernel/arm/splash_text.h: pre-rendered text
bitmaps (alpha) for the kernel boot splash.

The kernel has no font engine; the wordmark and stage labels are
rasterised ONCE here with PIL + DejaVu (permissive license) and
blitted by gpu.c with a chosen colour. Rerun after changing the
strings/sizes, then commit the regenerated header.

Usage: scripts/gen-splash.py
"""
from PIL import Image, ImageDraw, ImageFont
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "kernel", "kernel", "arm", "splash_text.h")
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
REG = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

ITEMS = [
    # (symbol, text, font path, size)
    ("SPLASH_WORDMARK", "QaonicOS", BOLD, 40),
    ("SPLASH_TAGLINE", "MACH 3.0 - DEV BUILD", REG, 13),
    ("SPLASH_STAGE0", "kernel", REG, 13),
    ("SPLASH_STAGE1", "system checks", REG, 13),
    ("SPLASH_STAGE2", "network", REG, 13),
    ("SPLASH_STAGE3", "ready", REG, 13),
]


def render(text, path, size):
    font = ImageFont.truetype(path, size)
    tmp = Image.new("L", (400, 120), 0)
    d = ImageDraw.Draw(tmp)
    box = d.textbbox((0, 0), text, font=font)
    w = box[2] - box[0]
    h = box[3] - box[1]
    img = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(img)
    d.text((-box[0], -box[1]), text, fill=255, font=font)
    return img


lines = []
lines.append("/* splash_text.h -- pre-rendered splash text bitmaps.")
lines.append(" * Generated by scripts/gen-splash.py (PIL + DejaVu,")
lines.append(" * permissive license). Do not edit by hand. */")
lines.append("#ifndef QAON_SPLASH_TEXT_H")
lines.append("#define QAON_SPLASH_TEXT_H")
lines.append("")
for sym, text, path, size in ITEMS:
    img = render(text, path, size)
    data = list(img.tobytes())
    lines.append(f"/* \"{text}\" ({img.size[0]}x{img.size[1]}) */")
    lines.append(f"#define {sym}_W {img.size[0]}u")
    lines.append(f"#define {sym}_H {img.size[1]}u")
    lines.append(f"static const unsigned char {sym.lower()}"
                 f"[{len(data)}] = {{")
    for i in range(0, len(data), 16):
        chunk = ",".join(str(v) for v in data[i:i + 16])
        lines.append("\t" + chunk + ",")
    lines.append("};")
    lines.append("")
lines.append("#endif")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT)
