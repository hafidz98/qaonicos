#!/usr/bin/env python3
"""sign-update.py - Build a signed QaonicOS update package (QUP1).

Format (all integers little-endian):
  header: magic "QUP1" (4) | version u32 | payload_len u32 |
          signature (256, RSA-2048 PKCS#1 v1.5 over SHA-256)
  payload: payload_len bytes
Signed content: magic || version || payload_len || payload.

The signature is produced by `openssl dgst -sha256 -sign`, which
emits exactly the PKCS#1 v1.5 + DigestInfo encoding the kernel
verifier checks.

Usage:
  sign-update.py --key dev-key.pem --version N --payload FILE \
      --out pkg.bin [--header-out updkey.h] [--array-out pkgs.h]

--header-out writes the kernel public-key header (updkey.h).
--array-out writes a C array of the package (for test embeds).

WARNING: scripts/update-img/dev-key.pem is a DEVELOPMENT test
key, committed on purpose (like Android test keys). The release
key must never live on a build machine (PLAN-B5).
"""
import argparse, struct, subprocess, sys, tempfile, os

MAGIC = b"QUP1"


def build_package(key, version, payload):
    head3 = MAGIC + struct.pack("<II", version, len(payload))
    signed = head3 + payload
    with tempfile.NamedTemporaryFile(delete=False) as f:
        f.write(signed)
        tmp = f.name
    try:
        sig = subprocess.run(
            ["openssl", "dgst", "-sha256", "-sign", key, tmp],
            capture_output=True, check=True).stdout
    finally:
        os.unlink(tmp)
    if len(sig) != 256:
        raise SystemExit(f"signature is {len(sig)} bytes, want 256 (RSA-2048 key?)")
    return head3 + sig + payload


def modulus_bytes(key):
    txt = subprocess.run(["openssl", "pkey", "-in", key, "-text", "-noout"],
                         capture_output=True, check=True, text=True).stdout
    grab, out = False, []
    for line in txt.splitlines():
        if line.strip() == "modulus:":
            grab = True
            continue
        if grab:
            if "Exponent" in line:
                break
            out.extend(line.replace(":", " ").split())
    raw = bytes(int(x, 16) for x in out)
    # openssl prints a leading 00 when the top bit is set.
    if len(raw) == 257 and raw[0] == 0:
        raw = raw[1:]
    return raw


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--key", required=True)
    ap.add_argument("--version", type=int, required=True)
    ap.add_argument("--payload", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--header-out")
    ap.add_argument("--array-out")
    ap.add_argument("--array-name", default="pkg_data")
    a = ap.parse_args()

    payload = open(a.payload, "rb").read()
    pkg = build_package(a.key, a.version, payload)
    with open(a.out, "wb") as f:
        f.write(pkg)
    print(f"package: {a.out} ({len(pkg)} bytes, version {a.version}, "
          f"payload {len(payload)} bytes)")

    if a.header_out:
        mod = modulus_bytes(a.key)
        assert len(mod) == 256, len(mod)
        lines = ", ".join(f"0x{b:02x}" for b in mod)
        with open(a.header_out, "w") as f:
            f.write("/* Generated by sign-update.py -- DEV test key "
                    "modulus (RSA-2048, e=65537). */\n")
            f.write("static const unsigned char upd_pubkey_mod[256] = {\n")
            for i in range(0, 256, 12):
                f.write("\t" + ", ".join(
                    f"0x{b:02x}" for b in mod[i:i + 12]) + ",\n")
            f.write("};\n")
        print(f"public key header: {a.header_out}")

    if a.array_out:
        with open(a.array_out, "w") as f:
            f.write(f"/* Generated by sign-update.py -- signed QUP1 "
                    f"package, version {a.version}. */\n")
            f.write(f"static const unsigned char {a.array_name}[] = {{\n")
            for i in range(0, len(pkg), 12):
                f.write("\t" + ", ".join(
                    f"0x{b:02x}" for b in pkg[i:i + 12]) + ",\n")
            f.write("};\n")
            f.write(f"static const unsigned int {a.array_name}_len = "
                    f"{len(pkg)}u;\n")
        print(f"package array: {a.array_out}")


if __name__ == "__main__":
    main()
